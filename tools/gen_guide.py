"""Regenerate the command reference at the end of deskisle/agent/GUIDE.md from the schema.

    python tools/gen_guide.py          rewrite the section
    python tools/gen_guide.py --check  exit 1 when it is out of date (used by the tests)
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from deskisle.agent.schema import COMMANDS  # noqa: E402

GUIDE = ROOT / "deskisle" / "agent" / "GUIDE.md"
BEGIN = "<!-- commands:begin (generated by tools/gen_guide.py) -->"
END = "<!-- commands:end -->"
SKIP = {"wait", "dry_run"}


def reference() -> str:
    lines = [BEGIN, "## Command reference", "",
             "`*` = required argument, ⚠ = asks the user first (`wait`, `dry_run` accepted). "
             "`deskisle-cli help <command>` shows types and descriptions.", ""]
    category = None
    for spec in COMMANDS:
        if spec["category"] != category:
            category = spec["category"]
            lines.append("**{0}**".format(category))
            lines.append("")
        params = ", ".join(key + ("*" if key in spec["required"] else "")
                           for key in spec["params"] if key not in SKIP)
        lines.append("* `{0}`{1} — {2}{3}{4}".format(
            spec["name"], " ⚠" if spec["destructive"] else "", spec["title"],
            " ({0})".format(params) if params else "", ". " + spec["description"].rstrip(".") + "."))
        if spec is COMMANDS[-1] or COMMANDS[COMMANDS.index(spec) + 1]["category"] != category:
            lines.append("")
    lines.append(END)
    return "\n".join(lines) + "\n"


def updated(text: str) -> str:
    if BEGIN in text and END in text:
        head = text[:text.index(BEGIN)]
        tail = text[text.index(END) + len(END):].lstrip("\n")
        return head + reference() + (("\n" + tail) if tail else "")
    return text.rstrip("\n") + "\n\n" + reference()


def main(argv: list[str]) -> int:
    text = GUIDE.read_text(encoding="utf-8")
    new = updated(text)
    if "--check" in argv:
        return 0 if new == text else 1
    if new != text:
        GUIDE.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
